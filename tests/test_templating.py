def test_strict_undefined_turns_a_template_typo_into_a_failure(
    repo: Path, tmp_path: Path, settings
) -> None:
    broken = tmp_path / "templates" / "broken"
    broken.mkdir(parents=True)
    (broken / "template.yaml").write_text(
        "name: broken\nversion: v1\nbase_image: scratch\n"
        "variables:\n  port:\n    kind: port\n",
        encoding="utf-8",
    )
    (broken / "Dockerfile.j2").write_text(
        "FROM {{ base_image }}\nEXPOSE {{ typo_variable }}\n", encoding="utf-8"
    )
    settings.BUILD_TEMPLATES_ROOT = str(tmp_path / "templates")

    with pytest.raises(BuildError) as exc_info:
        render_dockerfile(values(application_type="broken"), repo)

    assert exc_info.value.error_code == ErrorCode.TEMPLATE_RENDER_FAILED


def test_template_name_must_match_its_directory(
    repo: Path, tmp_path: Path, settings
) -> None:
    mismatched = tmp_path / "templates" / "django"
    mismatched.mkdir(parents=True)
    (mismatched / "template.yaml").write_text(
        "name: not-django\nversion: v1\nbase_image: scratch\n"
        "variables:\n  port:\n    kind: port\n",
        encoding="utf-8",
    )
    (mismatched / "Dockerfile.j2").write_text("FROM {{ base_image }}\n", encoding="utf-8")
    settings.BUILD_TEMPLATES_ROOT = str(tmp_path / "templates")

    with pytest.raises(BuildError) as exc_info:
        load_template_spec("django")

    assert exc_info.value.error_code == ErrorCode.TEMPLATE_RENDER_FAILED
